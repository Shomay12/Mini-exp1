"""Top-level research orchestration, evidence package, health, and config schemas."""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field

from web_intelligence.app.schemas.documents import SourceRecord
from web_intelligence.app.schemas.evidence import (
    ClaimConflict,
    CoverageAnalysis,
    CoverageStatus,
    EvidenceItem,
    ExtractedClaim,
)
from web_intelligence.app.schemas.search import (
    DisclosedSearchQuery,
    ProviderDiagnostic,
    ProviderStatus,
)


class ResearchStatus(str, Enum):
    """Lifecycle states of a research job."""

    PENDING = "pending"
    PLANNING = "planning"
    SEARCHING = "searching"
    RETRIEVING = "retrieving"
    PROCESSING = "processing"
    COMPLETED = "completed"
    FAILED = "failed"


class SearchIntent(str, Enum):
    """Deterministic classification of query intent."""

    FACTUAL = "factual"
    COMPARISON = "comparison"
    TEMPORAL = "temporal"
    EXPLORATORY = "exploratory"
    VERIFICATION = "verification"


class PlannedQuery(BaseModel):
    """A single sub-query generated by the query planner."""

    query: str
    intent: SearchIntent
    subtopic: str
    rationale: str


class QueryPlan(BaseModel):
    """Structured decomposition of the original natural-language query."""

    original_query: str
    normalized_query: str
    intent: SearchIntent
    topics: list[str] = Field(default_factory=list)
    keywords: list[str] = Field(default_factory=list)
    subtopics: list[str] = Field(default_factory=list)
    planned_queries: list[PlannedQuery] = Field(default_factory=list)
    planner_name: str = "deterministic_baseline_v1"


class ResearchRequest(BaseModel):
    """Input payload for POST /api/v1/research."""

    query: str = Field(..., min_length=2, max_length=2000)
    max_results_per_query: int = Field(default=5, ge=1, le=20)
    max_fetch_urls: int = Field(default=8, ge=1, le=25)
    providers: list[str] | None = None
    chunk_target_tokens: int | None = Field(default=None, ge=40, le=1000)


class ResearchProgress(BaseModel):
    """Execution progress telemetry for UI inspection."""

    current_stage: str = "pending"
    completed_stages: list[str] = Field(default_factory=list)
    queries_planned: int = 0
    urls_found: int = 0
    documents_fetched: int = 0
    documents_processed: int = 0
    duplicates_removed: int = 0
    evidence_items_count: int = 0


class ResearchMetadata(BaseModel):
    """Aggregate execution counts and transparency metadata for a research package."""

    retrieved_sources: int = 0
    processed_documents: int = 0
    duplicate_documents: int = 0
    failed_documents: int = 0
    evidence_items: int = 0
    claims_extracted: int = 0
    conflicts_detected: int = 0
    total_token_estimate: int = 0
    retrieved_at: datetime
    provider_diagnostics: list[ProviderDiagnostic] = Field(default_factory=list)
    privacy_notice: str = ""


class ResearchPackage(BaseModel):
    """Model-independent structured evidence package prepared for downstream local LLMs."""

    research_id: str
    original_query: str
    research_status: ResearchStatus
    query_plan: QueryPlan | None = None
    search_queries: list[DisclosedSearchQuery] = Field(default_factory=list)
    sources: list[SourceRecord] = Field(default_factory=list)
    evidence: list[EvidenceItem] = Field(default_factory=list)
    claims: list[ExtractedClaim] = Field(default_factory=list)
    conflicts: list[ClaimConflict] = Field(default_factory=list)
    coverage: CoverageAnalysis = Field(default_factory=CoverageAnalysis)
    metadata: ResearchMetadata
    progress: ResearchProgress = Field(default_factory=ResearchProgress)
    error_message: str | None = None


class ResearchRunSummary(BaseModel):
    """Compact summary for listing local research history."""

    research_id: str
    original_query: str
    research_status: ResearchStatus
    created_at: datetime
    retrieved_sources: int = 0
    evidence_items: int = 0
    conflicts_detected: int = 0
    coverage_status: CoverageStatus = CoverageStatus.INSUFFICIENT


class HealthResponse(BaseModel):
    """Response for GET /api/v1/health."""

    status: str
    database_ready: bool
    cloud_llm_required: bool = False
    providers: list[ProviderStatus] = Field(default_factory=list)
    timestamp: datetime


class SafeConfigResponse(BaseModel):
    """Response for GET /api/v1/config with zero secret values."""

    config: dict[str, Any]
